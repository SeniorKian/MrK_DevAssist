"""nftables ruleset generation and the fixed-argv ``nft`` runner.

Only the table ``inet mrk`` is ever named. Rules are applied atomically with
``nft -f FILE`` where FILE is generated here from validated ``ipaddress`` objects;
no shell is involved and no other argv shape can be executed.
"""

from __future__ import annotations

import hashlib
import json
import os
import secrets
import subprocess  # noqa: S404 - fixed argv only, see NftRunner.run
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Protocol

from .addresses import (
    AddressError,
    IPNetwork,
    check_allow_shape,
    check_block_shape,
    drop_covered,
    element,
    parse_network,
)
from .ports import PortError, PortPolicy, render_chains, render_sets

TABLE_FAMILY = "inet"
TABLE_NAME = "mrk"
SET_ALLOW_V4 = "mrk_allow_v4"
SET_ALLOW_V6 = "mrk_allow_v6"
SET_BLOCK_V4 = "mrk_block_v4"
SET_BLOCK_V6 = "mrk_block_v6"
CHAIN_NAME = "mrk_prerouting"
MODES = ("off", "dry_run", "enforce")
MAX_ALLOW = 1024
MAX_BLOCKS = 65536
MAX_TIMEOUT_SECONDS = 400 * 24 * 3600
DEFAULT_NFT = "/usr/sbin/nft"
COMMAND_TIMEOUT_SECONDS = 15.0
HEADER = "# Generated by mrk-firewall. Only the table inet mrk is managed here.\n"


class DesiredStateError(ValueError):
    def __init__(self, message: str, code: str = "invalid_state") -> None:
        super().__init__(message)
        self.code = code


@dataclass(frozen=True, slots=True)
class Block:
    network: IPNetwork
    expires_at: int | None  # epoch seconds; None = no timeout


@dataclass(slots=True)
class DesiredState:
    mode: str = "dry_run"
    allow: list[IPNetwork] = field(default_factory=list)
    blocks: list[Block] = field(default_factory=list)
    # Port policy (docs/45). None = not managed; it has its own on/off switch and is
    # rendered whenever it is enabled, independent of the dynamic-defense mode.
    ports: PortPolicy | None = None

    @classmethod
    def from_payload(cls, payload: object, *, now: float | None = None) -> DesiredState:
        """Strictly validate an apply request (or the persisted state file)."""
        if not isinstance(payload, dict):
            raise DesiredStateError("state must be an object")
        unknown = set(payload) - {"mode", "allow", "blocks", "ports"}
        if unknown:
            raise DesiredStateError(f"unknown field: {sorted(unknown)[0]}")
        mode = payload.get("mode")
        if mode not in MODES:
            raise DesiredStateError("mode must be off, dry_run or enforce", "invalid_mode")
        allow_raw = payload.get("allow", [])
        blocks_raw = payload.get("blocks", [])
        if not isinstance(allow_raw, list) or len(allow_raw) > MAX_ALLOW:
            raise DesiredStateError("allow must be a list of at most 1024 networks")
        if not isinstance(blocks_raw, list) or len(blocks_raw) > MAX_BLOCKS:
            raise DesiredStateError("blocks must be a list of at most 65536 entries")
        current = int(time.time() if now is None else now)
        allow: list[IPNetwork] = []
        try:
            for item in allow_raw:
                network = parse_network(item)
                check_allow_shape(network)
                allow.append(network)
            blocks: list[Block] = []
            for item in blocks_raw:
                if not isinstance(item, dict) or set(item) - {"cidr", "expires_at"}:
                    raise DesiredStateError("each block must be {cidr, expires_at}")
                network = parse_network(item.get("cidr"))
                check_block_shape(network)
                expires = item.get("expires_at")
                if expires is not None and (
                    not isinstance(expires, int) or isinstance(expires, bool) or expires < 0
                ):
                    raise DesiredStateError("expires_at must be an integer or null")
                if expires is not None and expires <= current:
                    continue  # already expired: silently dropped
                blocks.append(Block(network, expires))
        except AddressError as exc:
            raise DesiredStateError(str(exc), exc.code) from exc
        ports: PortPolicy | None = None
        if payload.get("ports") is not None:
            try:
                ports = PortPolicy.from_payload(payload["ports"], now=current)
            except PortError as exc:
                raise DesiredStateError(str(exc), exc.code) from exc
        return cls(mode=mode, allow=allow, blocks=blocks, ports=ports)

    def ports_active(self) -> bool:
        return self.ports is not None and self.ports.enabled

    def to_payload(self) -> dict[str, Any]:
        # "ports" only when managed, so states without it hash exactly as before and an
        # older helper never sees an unknown field.
        extra: dict[str, Any] = {} if self.ports is None else {"ports": self.ports.to_payload()}
        return {
            **extra,
            "mode": self.mode,
            "allow": sorted({str(item) for item in self.allow}),
            "blocks": sorted(
                ({"cidr": str(item.network), "expires_at": item.expires_at}
                 for item in self.blocks),
                key=lambda entry: (entry["cidr"], entry["expires_at"] or 0),
            ),
        }

    def state_hash(self) -> str:
        canonical = json.dumps(self.to_payload(), sort_keys=True, separators=(",", ":"))
        return hashlib.sha256(canonical.encode()).hexdigest()


def effective_blocks(blocks: list[Block]) -> list[Block]:
    """Collapse overlapping blocks; a covering network keeps the longest expiry."""
    by_network: dict[IPNetwork, int | None] = {}
    for block in blocks:
        if block.network in by_network:
            previous = by_network[block.network]
            if previous is None or block.expires_at is None:
                by_network[block.network] = None
            else:
                by_network[block.network] = max(previous, block.expires_at)
        else:
            by_network[block.network] = block.expires_at
    kept = drop_covered(by_network)
    return [Block(network, by_network[network]) for network in kept]


def _set(name: str, kind: str, elements: list[str], *, timeout: bool) -> str:
    flags = "interval, timeout" if timeout else "interval"
    lines = [f"\tset {name} {{", f"\t\ttype {kind}", f"\t\tflags {flags}"]
    if elements:
        joined = ",\n".join(f"\t\t\t{item}" for item in elements)
        lines.append(f"\t\telements = {{\n{joined}\n\t\t}}")
    lines.append("\t}")
    return "\n".join(lines)


def _block_element(block: Block, now: int) -> str:
    text = element(block.network)
    if block.expires_at is None:
        return text
    remaining = min(max(block.expires_at - now, 1), MAX_TIMEOUT_SECONDS)
    return f"{text} timeout {remaining}s"


def render_ruleset(state: DesiredState, *, now: float | None = None,
                   dynamic: bool = True) -> str:
    """Return the full ``nft -f`` input (golden-tested).

    ``add table inet mrk`` + ``delete table inet mrk`` first makes the file idempotent
    (create-if-missing, then drop) inside the same atomic transaction, so a re-apply
    replaces our table and nothing else. Allow sets are evaluated first; ``accept``
    only ends *our* chain, every other table still sees the packet.

    ``dynamic`` renders the block/allow sets and the prerouting chain (dynamic defense
    in enforce mode); an enabled port policy adds its sets and chains after them.
    """
    current = int(time.time() if now is None else now)
    parts: list[str] = []
    if dynamic:
        parts.append(_render_dynamic(state, current))
    if state.ports is not None and state.ports.enabled:
        parts.extend(render_sets(state.ports, current))
        parts.extend(render_chains(state.ports, current))
    body = "\n".join(parts)
    return (
        HEADER
        + f"add table {TABLE_FAMILY} {TABLE_NAME}\n"
        + f"delete table {TABLE_FAMILY} {TABLE_NAME}\n"
        + f"table {TABLE_FAMILY} {TABLE_NAME} {{\n{body}\n}}\n"
    )


def render_effective(state: DesiredState, *, now: float | None = None) -> str | None:
    """What the helper loads for this state; None = our table is removed."""
    if state.mode == "enforce":
        return render_ruleset(state, now=now)
    if state.ports_active():
        return render_ruleset(state, now=now, dynamic=False)
    return None


def _render_dynamic(state: DesiredState, current: int) -> str:
    allow = drop_covered(state.allow)
    blocks = effective_blocks(state.blocks)
    allow4 = [element(item) for item in allow if item.version == 4]
    allow6 = [element(item) for item in allow if item.version == 6]
    block4 = [_block_element(item, current) for item in blocks if item.network.version == 4]
    block6 = [_block_element(item, current) for item in blocks if item.network.version == 6]
    return "\n".join(
        [
            _set(SET_ALLOW_V4, "ipv4_addr", allow4, timeout=False),
            _set(SET_ALLOW_V6, "ipv6_addr", allow6, timeout=False),
            _set(SET_BLOCK_V4, "ipv4_addr", block4, timeout=True),
            _set(SET_BLOCK_V6, "ipv6_addr", block6, timeout=True),
            f"\tchain {CHAIN_NAME} {{",
            "\t\ttype filter hook prerouting priority raw; policy accept;",
            f"\t\tip saddr @{SET_ALLOW_V4} accept",
            f"\t\tip6 saddr @{SET_ALLOW_V6} accept",
            f"\t\tip saddr @{SET_BLOCK_V4} counter drop",
            f"\t\tip6 saddr @{SET_BLOCK_V6} counter drop",
            "\t}",
        ]
    )


def render_delete() -> str:
    """Idempotent removal of our table only (works whether or not it exists)."""
    return (
        HEADER
        + f"add table {TABLE_FAMILY} {TABLE_NAME}\n"
        + f"delete table {TABLE_FAMILY} {TABLE_NAME}\n"
    )


# ----- runner ---------------------------------------------------------------


@dataclass(frozen=True, slots=True)
class NftResult:
    returncode: int
    stdout: str
    stderr: str


class Runner(Protocol):
    def run(self, args: list[str]) -> NftResult: ...

    def available(self) -> bool: ...


LIST_ARGS = ["-j", "list", "table", TABLE_FAMILY, TABLE_NAME]


def check_args(args: list[str], state_dir: Path) -> None:
    """Allow only the argv shapes this module produces."""
    if args == LIST_ARGS or args == ["--version"]:
        return
    if (len(args) == 2 and args[0] == "-f") or (len(args) == 3 and args[:2] == ["-c", "-f"]):
        path = Path(args[-1])
        if path.parent == state_dir and path.name.startswith(".ruleset-") and path.suffix == ".nft":
            return
    raise ValueError("nft argv is not on the allowlist")


class NftRunner:
    """Runs ``nft`` with a fixed argv list (never a shell)."""

    def __init__(self, binary: str, state_dir: Path) -> None:
        if not os.path.isabs(binary):
            raise ValueError("MRK_FIREWALL_NFT must be an absolute path")
        self.binary = binary
        self.state_dir = state_dir

    def available(self) -> bool:
        return os.path.isfile(self.binary) and os.access(self.binary, os.X_OK)

    def run(self, args: list[str]) -> NftResult:
        check_args(args, self.state_dir)
        if not self.available():
            return NftResult(127, "", "nft binary not found")
        completed = subprocess.run(  # noqa: S603 - validated fixed argv, shell=False
            [self.binary, *args],
            capture_output=True,
            text=True,
            timeout=COMMAND_TIMEOUT_SECONDS,
            check=False,
            env={"PATH": "/usr/sbin:/usr/bin:/sbin:/bin", "LC_ALL": "C"},
        )
        return NftResult(completed.returncode, completed.stdout[:1_000_000],
                         completed.stderr[:4000])


class NftError(RuntimeError):
    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code = code
        self.message = message


def _missing_table(result: NftResult) -> bool:
    text = result.stderr.lower()
    return "no such file or directory" in text or "does not exist" in text


class NftManager:
    """Applies a DesiredState through a Runner. Thread-unsafe: callers serialize."""

    def __init__(self, runner: Runner, state_dir: Path) -> None:
        self.runner = runner
        self.state_dir = state_dir

    def _run_file(self, text: str, *, check: bool = False) -> NftResult:
        self.state_dir.mkdir(parents=True, exist_ok=True)
        path = self.state_dir / f".ruleset-{secrets.token_hex(6)}.nft"
        descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        try:
            with os.fdopen(descriptor, "w", encoding="ascii", newline="\n") as handle:
                handle.write(text)
            if check:
                checked = self.runner.run(["-c", "-f", str(path)])
                if checked.returncode != 0:
                    return checked
            return self.runner.run(["-f", str(path)])
        finally:
            path.unlink(missing_ok=True)

    def apply(self, state: DesiredState, *, now: float | None = None) -> dict[str, Any]:
        """enforce or an enabled port policy -> ``nft -c -f`` then ONE atomic ``nft -f``
        replacing our table; otherwise our table is removed. A failed check or load
        leaves the kernel exactly as it was."""
        text = render_effective(state, now=now)
        if text is None:
            text, action = render_delete(), "delete_table"
        else:
            action = "replace_table"
        if not self.runner.available():
            if action == "replace_table":
                raise NftError("nft_unavailable", "the nft binary is not installed")
            return {"action": "none", "nft_available": False}
        result = self._run_file(text, check=action == "replace_table")
        if result.returncode != 0:
            raise NftError("nft_failed", result.stderr.strip()[:500] or "nft failed")
        return {"action": action, "nft_available": True}

    def delete_table(self) -> dict[str, Any]:
        """Last resort used by recovery: remove our table (fail open)."""
        if not self.runner.available():
            return {"action": "none", "nft_available": False}
        result = self._run_file(render_delete())
        if result.returncode != 0:
            raise NftError("nft_failed", result.stderr.strip()[:500] or "nft failed")
        return {"action": "delete_table", "nft_available": True}

    def table_status(self) -> dict[str, Any]:
        """Summarize ``nft -j list table inet mrk`` (sets, element and drop counters)."""
        if not self.runner.available():
            return {"nft_available": False, "present": False}
        result = self.runner.run(list(LIST_ARGS))
        if result.returncode != 0:
            if _missing_table(result):
                return {"nft_available": True, "present": False}
            return {"nft_available": True, "present": None,
                    "error": result.stderr.strip()[:300]}
        return {"nft_available": True, "present": True, **summarize_listing(result.stdout)}


def summarize_listing(text: str) -> dict[str, Any]:
    try:
        payload = json.loads(text)
    except ValueError:
        return {"error": "unparseable nft output"}
    sets: dict[str, int] = {}
    dropped_packets = 0
    dropped_bytes = 0
    items = payload.get("nftables", []) if isinstance(payload, dict) else []
    for item in items if isinstance(items, list) else []:
        if not isinstance(item, dict):
            continue
        set_obj = item.get("set")
        if isinstance(set_obj, dict) and isinstance(set_obj.get("name"), str):
            elements = set_obj.get("elem")
            sets[set_obj["name"]] = len(elements) if isinstance(elements, list) else 0
        rule = item.get("rule")
        if isinstance(rule, dict) and isinstance(rule.get("expr"), list):
            exprs = rule["expr"]
            if any(isinstance(expr, dict) and "drop" in expr for expr in exprs):
                for expr in exprs:
                    counter = expr.get("counter") if isinstance(expr, dict) else None
                    if isinstance(counter, dict):
                        dropped_packets += int(counter.get("packets", 0) or 0)
                        dropped_bytes += int(counter.get("bytes", 0) or 0)
    return {"sets": sets, "dropped_packets": dropped_packets, "dropped_bytes": dropped_bytes}

"""What the add-service wizard can install and how (docs/44).

The panel runs alone first. Every other MrK service is its own image and its own
Compose stack, deployed next to the panel with Dokploy, Coolify or plain
``docker compose``. This file is the single source for those stacks: the wizard
serves the Compose file below verbatim and fills a ``.env`` for it, so the text
the operator pastes is always the text that was reviewed here.

Shared plumbing between the stacks (all created by the panel stack, which is
deployed first; the service stacks only reference them):

- network ``mrk-net`` (internal, no egress): the panel reaches HTTP services by
  their alias, e.g. ``http://mrk-agent:7070``;
- volume ``mrk-dns-run``: admin socket + token of the DNS engine;
- volume ``mrk-firewall-run``: Unix socket of the firewall helper.

Pure data and string rendering only: no I/O, so it is easy to test.
"""


_ENV_NAME = re.compile(r"^[A-Z][A-Z0-9_]{0,63}$")


def panel_is_native() -> bool:
    """The panel runs under systemd, not Docker (scripts/install-native.sh)."""
    return os.getenv("MRK_PANEL_RUNTIME", "").strip().lower() == "native"


def _swap(text: str, old: str, new: str) -> str:
    if old not in text:  # pragma: no cover - guards the templates above
        raise RuntimeError(f"compose template changed: {old!r}")
    return text.replace(old, new)


_EXTERNAL_NET = "\nnetworks:\n  mrk-net:\n    name: mrk-net\n    external: true\n"


def _native_registry(text: str, service: str, data_dir: Path | None) -> str:
    """npm/PyPI next to a native panel: share the panel's own data folder."""
    # The native panel sees its data as /data (systemd BindPaths); the containers
    # need the host path, which the native installer records.
    host_root = os.getenv("MRK_HOST_DATA_DIR", "").strip()
    root = Path(host_root or data_dir or "/var/lib/devassist") / service
    text = _swap(text, f"      - mrk-{service}-data:/data/{service}\n",
                 f"      - {root.as_posix()}:/data/{service}\n")
    text = _swap(text, f"\nvolumes:\n  mrk-{service}-data:\n    name: mrk-{service}-data\n"
                 "    external: true\n", "")
    text = _swap(text, _EXTERNAL_NET, "")
    if service == "npm":
        return _swap(
            text,
            "    networks:\n      # default: Internet access for the npm upstreams.\n"
            "      default:\n      mrk-net:\n        aliases: [mrk-npm]\n",
            "",
        )
    # devpi must reach the panel's PyPI router on the host's loopback.
    text = _swap(
        text,
        '    ports:\n      - "${MRK_PYPI_BIND:-127.0.0.1}:${MRK_PYPI_PORT:-3141}:3141"\n'
        "    networks:\n      default:\n      mrk-net:\n        aliases: [mrk-pypi]\n",
        "    network_mode: host\n",
    )
    text = _swap(text, "${MRK_PYPI_UPSTREAM_URL:-http://mrk-panel:3142/simple/}",
                 "${MRK_PYPI_UPSTREAM_URL:-http://127.0.0.1:3142/simple/}")
    return _swap(
        text,
        "      MRK_PYPI_THREADS: ${MRK_PYPI_THREADS:-16}\n",
        "      MRK_PYPI_THREADS: ${MRK_PYPI_THREADS:-16}\n"
        "      MRK_PYPI_LISTEN_HOST: ${MRK_PYPI_BIND:-127.0.0.1}\n"
        "      MRK_PYPI_PORT: ${MRK_PYPI_PORT:-3141}\n",
    )


def compose_for(item: InstallDef, data_dir: Path | None = None) -> str:
    """The Compose file for this panel.

    A native panel is not on Docker's mrk-net, so the HTTP services publish their
    admin port on loopback only and the socket services use host folders the
    native installer created (/run/mrk-dns, /run/mrk-firewall).
    """
    text = item.compose
    if not panel_is_native():
        return text
    if item.id == "agent":
        text = _swap(
            text,
            "    networks:\n      mrk-net:\n        aliases: [mrk-agent]\n",
            "    ports:\n      # Loopback only: the panel runs on this host without Docker.\n"
            '      - "127.0.0.1:7070:7070"\n',
        )
        text = _swap(text, _EXTERNAL_NET, "")
    elif item.id == "s3":
        text = _swap(
            text, "    networks:\n      default:\n      mrk-net:\n        aliases: [mrk-s3]\n", ""
        )
        published = '      - "${MRK_S3_BIND:-127.0.0.1}:${MRK_S3_PORT:-9000}:9000"\n'
        text = _swap(
            text,
            published,
            published + "      # Admin API for the panel on this host, loopback only.\n"
            '      - "127.0.0.1:9001:9001"\n',
        )
        text = _swap(text, _EXTERNAL_NET, "")
    elif item.id in {"npm", "pypi"}:
        text = _native_registry(text, item.id, data_dir)
    elif item.id in {"git", "registry"}:
        # Ports are already on loopback, where a native panel reaches them.
        alias = f"mrk-{item.id}"
        text = _swap(
            text,
            "    networks:\n      # default: Internet access for "
            + ("mirrors of GitHub/GitLab repositories.\n" if item.id == "git"
               else "the mirrored registries.\n")
            + f"      default:\n      mrk-net:\n        aliases: [{alias}]\n",
            "",
        )
        text = _swap(text, _EXTERNAL_NET, "")
        if item.id == "registry":
            host_root = os.getenv("MRK_HOST_DATA_DIR", "").strip()
            root = Path(host_root or data_dir or "/var/lib/devassist") / "registry"
            text = _swap(text, "      - mrk-registry-config:/etc/zot:ro\n",
                         f"      - {root.as_posix()}:/etc/zot:ro\n")
            text = _swap(text, "  mrk-registry-config:\n    name: mrk-registry-config\n"
                         "    external: true\n", "")
    elif item.id == "dns":
        text = _swap(text, "      - mrk-dns-run:/run/mrk-dns\n", "      - /run/mrk-dns:/run/mrk-dns\n")
        text = _swap(text, "  mrk-dns-run:\n    name: mrk-dns-run\n    external: true\n", "")
    elif item.id == "firewall":
        text = _swap(
            text,
            "      - mrk-firewall-run:/run/mrk-firewall\n",
            "      - /run/mrk-firewall:/run/mrk-firewall\n",
        )
        text = _swap(
            text, "  mrk-firewall-run:\n    name: mrk-firewall-run\n    external: true\n", ""
        )
    return text



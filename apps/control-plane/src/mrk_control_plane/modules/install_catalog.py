_REGISTRY = re.compile(r"^[a-z0-9]+(?:[._-][a-z0-9]+)*(?::[0-9]{1,5})?(?:/[a-z0-9]+(?:[._-][a-z0-9]+)*)*$")
_TAG = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9_.-]{0,127}$")


def image_registry() -> str:
    value = os.getenv("MRK_IMAGE_REGISTRY", "").strip().rstrip("/").lower()
    return value if value and _REGISTRY.match(value) else DEFAULT_IMAGE_REGISTRY


def image_tag() -> str:
    """Tag of the service images: the panel's own release, so versions always match."""
    value = os.getenv("MRK_IMAGE_TAG", "").strip()
    return value if value and _TAG.match(value) else "latest"


def image_ref(service_id: str) -> str:
    return f"{image_registry()}/mrk-{service_id}:{image_tag()}"


@dataclass(frozen=True, slots=True)
class EnvField:
    name: str
    default: str
    help_fa: str
    help_en: str
    # Values the wizard lets the operator change before generating the files.
    editable: bool = True
    pattern: str = r"^[A-Za-z0-9_.,:/@%+=-]{0,200}$"


@dataclass(frozen=True, slots=True)
class InstallDef:
    id: str
    # "ready": image and stack exist; "planned": still bundled, split in a later release.
    availability: str
    # The stack must run on the panel's own server (shared Unix-socket volume or host access).
    same_host: bool
    needs_privileges_fa: str
    needs_privileges_en: str
    resources_fa: str
    resources_en: str
    compose: str
    env: tuple[EnvField, ...] = ()
    # Name of the generated pairing-key variable; None = the service needs no key.
    pairing_env: str | None = None
    default_url: str | None = None
    # Deployment targets offered in the wizard, in order.
    methods: tuple[str, ...] = ("dokploy", "coolify", "compose")
    notes_fa: tuple[str, ...] = field(default_factory=tuple)
    notes_en: tuple[str, ...] = field(default_factory=tuple)



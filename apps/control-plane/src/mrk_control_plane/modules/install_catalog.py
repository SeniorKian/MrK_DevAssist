_ENV_NAME = re.compile(r"^[A-Z][A-Z0-9_]{0,63}$")


def panel_is_native() -> bool:
    """The panel runs under systemd, not Docker (scripts/install-native.sh)."""
    return os.getenv("MRK_PANEL_RUNTIME", "").strip().lower() == "native"


def _swap(text: str, old: str, new: str) -> str:
    if old not in text:  # pragma: no cover - guards the templates above
        raise RuntimeError(f"compose template changed: {old!r}")
    return text.replace(old, new)


_EXTERNAL_NET = "\nnetworks:\n  mrk-net:\n    name: mrk-net\n    external: true\n"


def compose_for(item: InstallDef) -> str:
    """The Compose file for this panel.

    A native panel is not on Docker's mrk-net, so the HTTP services publish their
    admin port on loopback only and the socket services use host folders the
    native installer created (/run/mrk-dns, /run/mrk-firewall).
    """
    text = item.compose
    if not panel_is_native():
        return text
    if item.id == "agent":
        text = _swap(
            text,
            "    networks:\n      mrk-net:\n        aliases: [mrk-agent]\n",
            "    ports:\n      # Loopback only: the panel runs on this host without Docker.\n"
            '      - "127.0.0.1:7070:7070"\n',
        )
        text = _swap(text, _EXTERNAL_NET, "")
    elif item.id == "s3":
        text = _swap(
            text, "    networks:\n      default:\n      mrk-net:\n        aliases: [mrk-s3]\n", ""
        )
        published = '      - "${MRK_S3_BIND:-127.0.0.1}:${MRK_S3_PORT:-9000}:9000"\n'
        text = _swap(
            text,
            published,
            published + "      # Admin API for the panel on this host, loopback only.\n"
            '      - "127.0.0.1:9001:9001"\n',
        )
        text = _swap(text, _EXTERNAL_NET, "")
    elif item.id == "dns":
        text = _swap(text, "      - mrk-dns-run:/run/mrk-dns\n", "      - /run/mrk-dns:/run/mrk-dns\n")
        text = _swap(text, "  mrk-dns-run:\n    name: mrk-dns-run\n    external: true\n", "")
    elif item.id == "firewall":
        text = _swap(
            text,
            "      - mrk-firewall-run:/run/mrk-firewall\n",
            "      - /run/mrk-firewall:/run/mrk-firewall\n",
        )
        text = _swap(
            text, "  mrk-firewall-run:\n    name: mrk-firewall-run\n    external: true\n", ""
        )
    return text


NATIVE_URLS = {"agent": "http://127.0.0.1:7070", "s3": "http://127.0.0.1:9001"}


def default_url(item: InstallDef) -> str | None:
    if panel_is_native():
        return NATIVE_URLS.get(item.id, item.default_url)
    return item.default_url


def resolve_env(item: InstallDef, overrides: dict[str, str]) -> dict[str, str]:
    """Validated env values: defaults, then allowed overrides. Raises ValueError(field)."""
    values: dict[str, str] = {}
    known = {entry.name: entry for entry in item.env}
    for name in overrides:
        if name not in known or not known[name].editable:
            raise ValueError(name)
    for entry in item.env:
        value = overrides.get(entry.name, entry.default)
        value = value.strip() if isinstance(value, str) else ""
        if not re.match(entry.pattern, value):
            raise ValueError(entry.name)
        values[entry.name] = value
    return values


def render_env(item: InstallDef, values: dict[str, str], pairing_key: str | None) -> str:
    lines = [
        f"# MrK DevAssist - {item.id} (generated by the panel). Keep this file private.",
        f"MRK_IMAGE={image_ref(item.id)}",
    ]
    if item.pairing_env:
        if pairing_key is None:
            raise ValueError("pairing key required")
        lines.append(f"{item.pairing_env}={pairing_key}")
    for name, value in values.items():
        if not _ENV_NAME.match(name):  # pragma: no cover - catalog is static
            raise ValueError(name)
        lines.append(f"{name}={value}")
    return "\n".join(lines) + "\n"


def public_item(item: InstallDef) -> dict[str, object]:
    return {
        "id": item.id,
        "availability": item.availability,
        "same_host": item.same_host,
        "image": image_ref(item.id) if item.availability == "ready" else None,
        "needs_privileges_fa": item.needs_privileges_fa,
        "needs_privileges_en": item.needs_privileges_en,
        "resources_fa": item.resources_fa,
        "resources_en": item.resources_en,
        "methods": list(item.methods) if item.availability == "ready" else [],
        "pairing": item.pairing_env is not None,
        "default_url": default_url(item),
        "panel_runtime": "native" if panel_is_native() else "docker",
        "env": [
            {
                "name": entry.name,
                "default": entry.default,
                "help_fa": entry.help_fa,
                "help_en": entry.help_en,
                "editable": entry.editable,
            }
            for entry in item.env
        ],
        "notes_fa": list(item.notes_fa),
        "notes_en": list(item.notes_en),
    }

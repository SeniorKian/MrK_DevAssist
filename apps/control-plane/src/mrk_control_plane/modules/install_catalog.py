def default_url(item: InstallDef) -> str | None:
    if panel_is_native():
        return NATIVE_URLS.get(item.id, item.default_url)
    return item.default_url


def resolve_env(item: InstallDef, overrides: dict[str, str]) -> dict[str, str]:
    """Validated env values: defaults, then allowed overrides. Raises ValueError(field)."""
    values: dict[str, str] = {}
    known = {entry.name: entry for entry in item.env}
    for name in overrides:
        if name not in known or not known[name].editable:
            raise ValueError(name)
    for entry in item.env:
        value = overrides.get(entry.name, entry.default)
        value = value.strip() if isinstance(value, str) else ""
        if not re.match(entry.pattern, value):
            raise ValueError(entry.name)
        values[entry.name] = value
    return values


def render_env(item: InstallDef, values: dict[str, str], pairing_key: str | None) -> str:
    lines = [f"# MrK DevAssist - {item.id} (generated by the panel). Keep this file private."]
    if item.upstream_image is None:
        lines.append(f"MRK_IMAGE={image_ref(item.id)}")
    if item.pairing_env:
        if pairing_key is None:
            raise ValueError("pairing key required")
        lines.append(f"{item.pairing_env}={pairing_key}")
    for name, value in values.items():
        if not _ENV_NAME.match(name):  # pragma: no cover - catalog is static
            raise ValueError(name)
        lines.append(f"{name}={value}")
    return "\n".join(lines) + "\n"


def public_item(item: InstallDef) -> dict[str, object]:
    return {
        "id": item.id,
        "availability": item.availability,
        "same_host": item.same_host,
        "image": (item.upstream_image or image_ref(item.id))
        if item.availability == "ready" else None,
        "needs_privileges_fa": item.needs_privileges_fa,
        "needs_privileges_en": item.needs_privileges_en,
        "resources_fa": item.resources_fa,
        "resources_en": item.resources_en,
        "methods": list(item.methods) if item.availability == "ready" else [],
        "pairing": item.pairing_env is not None,
        "default_url": default_url(item),
        "panel_runtime": "native" if panel_is_native() else "docker",
        "env": [
            {
                "name": entry.name,
                "default": entry.default,
                "help_fa": entry.help_fa,
                "help_en": entry.help_en,
                "editable": entry.editable,
            }
            for entry in item.env
        ],
        "notes_fa": list(item.notes_fa),
        "notes_en": list(item.notes_en),
    }

"""Registry entries for startup (environment) and build settings.

Ranges mirror the code that reads each variable, so a value the panel accepts
never stops a process from starting. ``reason`` marks entries the panel may not
write (see ``settings_registry.ENV_ONLY_REASONS``).
"""


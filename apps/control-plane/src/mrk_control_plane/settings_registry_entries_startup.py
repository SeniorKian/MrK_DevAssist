def env(
    key: str,
    group: str,
    type_: str,
    default: Any,
    env_name: str,
    label: tuple[str, str],
    description: tuple[str, str],
    *,
    reason: str | None = None,
    processes: tuple[str, ...] = CP,
    danger: str = "low",
    **extra: Any,
) -> SettingSpec:
    overridable = reason is None
    return SettingSpec(
        key=key,
        group=group,
        type=type_,
        default=default,
        label_fa=label[0],
        label_en=label[1],
        description_fa=description[0],
        description_en=description[1],
        source="startup",
        env=env_name,
        restart_required=True,
        danger=danger,
        write_permission=STARTUP_WRITE_PERMISSION if overridable else None,
        overridable=overridable,
        env_only_reason=reason,
        processes=processes,
        secret=type_ == "secret",
        **extra,
    )


def build(
    key: str, env_name: str, type_: str, label: tuple[str, str], description: tuple[str, str]
) -> SettingSpec:
    return SettingSpec(
        key=key,
        group="system",
        type=type_,
        default=None,
        label_fa=label[0],
        label_en=label[1],
        description_fa=description[0],
        description_en=description[1],
        source="build",
        env=env_name,
        restart_required=True,
        danger="none",
        env_only_reason="build",
        processes=("image",),
        nullable=True,
    )



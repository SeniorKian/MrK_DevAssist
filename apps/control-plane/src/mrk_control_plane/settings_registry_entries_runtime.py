MODULE_PERMISSIONS: dict[str, tuple[str, str]] = {
    "auth": ("user:read", "user:write"),
    "network": ("upstream:read", "upstream:write"),
    "monitoring": ("metrics:read", "agent:write"),
    "dokploy": ("dokploy:read", "dokploy:write"),
    "build_mirror": ("dokploy:read", "dokploy:write"),
    "updates": ("updates:read", "updates:write"),
    "dbadmin": ("db:read", "db:write"),
    "s3": ("s3:read", "s3:admin"),
    "server_backups": ("backup:server:read", "backup:server:write"),
    "firewall": ("firewall:read", "firewall:write"),
    "vuln": ("vuln:read", "vuln:write"),
    "notifications": ("notification:read", "notification:write"),
    "services": ("domains:read", "domains:write"),
    "dns": ("dns:read", "dns:admin"),
    "tenancy": ("user:read", "tenancy:admin"),
}


def rt(
    module: str,
    path: str,
    key: str,
    group: str,
    type_: str,
    default: Any,
    label: tuple[str, str],
    description: tuple[str, str],
    *,
    danger: str = "low",
    **extra: Any,
) -> SettingSpec:
    read, write = MODULE_PERMISSIONS[module]
    return SettingSpec(
        key=key,
        group=group,
        type=type_,
        default=default,
        label_fa=label[0],
        label_en=label[1],
        description_fa=description[0],
        description_en=description[1],
        source="runtime",
        module=module,
        path=tuple(path.split(".")),
        read_permission=read,
        write_permission=write,
        danger=danger,
        **extra,
    )


def k(
    key: str,
    group: str,
    type_: str,
    default: Any,
    label: tuple[str, str],
    description: tuple[str, str],
    *,
    read: str = "system:read",
    **extra: Any,
) -> SettingSpec:
    return SettingSpec(
        key=key,
        group=group,
        type=type_,
        default=default,
        label_fa=label[0],
        label_en=label[1],
        description_fa=description[0],
        description_en=description[1],
        source="constant",
        read_permission=read,
        write_permission=None,
        danger=extra.pop("danger", "none"),
        **extra,
    )



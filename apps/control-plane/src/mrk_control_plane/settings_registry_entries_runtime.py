"""Registry entries for runtime (panel) settings and for hard-coded constants.

Runtime entries name the module that owns the value (``module``) and the path of
the value inside that module's settings object (``path``). Ranges are copied
from each module's validator, which still runs on every write.
"""

from __future__ import annotations


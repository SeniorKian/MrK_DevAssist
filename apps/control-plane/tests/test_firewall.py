def helper_app(tmp_path: Path, runner: FakeRunner | None = None, **overrides):
    (tmp_path / "log" / "system").mkdir(parents=True, exist_ok=True)
    config = FirewallConfig(key=KEY, state_dir=tmp_path / "state", log_root=tmp_path / "log",
                            proc_net=tmp_path / "no-proc", **overrides)
    return create_firewall_app(config, runner=runner or FakeRunner())


def signed(client: TestClient, method: str, path: str, body: object = None):
    raw = b"" if body is None else json.dumps(body).encode()
    headers = signing.sign_headers(KEY, method, path, raw)
    return client.request(method, path, content=raw, headers=headers)


def test_helper_api_signatures_apply_signals_and_startup_reconcile(tmp_path: Path) -> None:
    runner = FakeRunner()
    with TestClient(helper_app(tmp_path, runner)) as client:
        # Startup with no state: our table is removed, nothing installed.
        assert runner.table is None and len(runner.files) == 1
        assert client.get("/v1/health").json() == {"status": "ok"}
        assert client.get("/v1/info").status_code == 401
        assert client.post("/v1/apply", json={}).status_code == 401
        assert client.get("/v1/other").status_code == 404
        info = signed(client, "GET", "/v1/info").json()
        assert info["mode"] == "dry_run" and info["table"]["present"] is False

        bad = signed(client, "POST", "/v1/apply", {"mode": "enforce",
                                                    "blocks": [{"cidr": "::1",
                                                                "expires_at": None}]})
        assert bad.status_code == 422 and bad.json()["error"] == "loopback"
        applied = signed(client, "POST", "/v1/apply", {
            "mode": "enforce", "allow": ["192.0.2.10"],
            "blocks": [{"cidr": "198.51.100.1", "expires_at": None}]}).json()
        assert applied["effective_mode"] == "enforce" and applied["action"] == "replace_table"
        assert "198.51.100.1" in runner.table
        state_file = tmp_path / "state" / "desired.json"
        assert json.loads(state_file.read_text())["mode"] == "enforce"

        auth = tmp_path / "log" / "system" / "auth.log"
        auth.write_text("start\n")
        sources = {"sources": [{"name": "sshd", "kind": "sshd",
                                "path": "/host/log/system/auth.log"}],
                   "sensitive_paths": ["/.env"]}
        first = signed(client, "POST", "/v1/signals", sources).json()
        assert first["signals"] == [] and first["sources"]["sshd"]["ok"] is True
        with auth.open("a") as handle:
            handle.write("Nov 8 h sshd[2]: Invalid user x from 203.0.113.9 port 1\n")
        second = signed(client, "POST", "/v1/signals", sources).json()
        assert [(s["kind"], s["ip"], s["source"]) for s in second["signals"]] == [
            ("ssh_invalid_user", "203.0.113.9", "sshd")]
        assert second["state_hash"] == applied["state_hash"]
        outside = signed(client, "POST", "/v1/signals", {"sources": [
            {"name": "x", "kind": "sshd", "path": "/etc/shadow"}]})
        assert outside.status_code == 422 and outside.json()["error"] == "invalid_source_path"

    # Restart: the persisted enforce state is re-applied without the control plane.
    runner2 = FakeRunner()
    with TestClient(helper_app(tmp_path, runner2)):
        assert runner2.table is not None and "198.51.100.1" in runner2.table



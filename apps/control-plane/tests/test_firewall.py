def test_ruleset_golden_text_and_overlap_collapse() -> None:
    state = DesiredState(
        mode="enforce",
        allow=[net("10.0.0.0/8"), net("10.1.0.0/16"), net("203.0.113.7")],
        blocks=[
            Block(net("198.51.100.0/24"), 1000 + 3600),
            Block(net("198.51.100.9"), None),  # covered by the /24 -> dropped
            Block(net("203.0.113.99"), None),
            Block(net("2001:db8::1"), 1060),
        ],
    )
    assert render_ruleset(state, now=1000) == GOLDEN
    assert render_delete().splitlines()[1:] == ["add table inet mrk", "delete table inet mrk"]
    # Only our table is ever named.
    for text in (GOLDEN, render_delete()):
        body = "\n".join(line for line in text.splitlines() if not line.startswith("#"))
        assert set(re.findall(r"\btable (\S+) (\S+)", body)) == {("inet", "mrk")}
        assert "ruleset" not in body and "flush" not in body


def test_address_parsing_and_shape_rules() -> None:
    assert str(net("::ffff:203.0.113.5")) == "203.0.113.5/32"
    assert str(net("198.51.100.77/24")) == "198.51.100.0/24"
    for bad in ("", "1.2.3", "1.2 .3.4", "fe80::1%eth0", "x" * 80, "1.2.3.4/33", None):
        with pytest.raises(AddressError):
            parse_network(bad)
    for wide, code in (("8.0.0.0/8", "prefix_too_broad"), ("127.0.0.1", "loopback"),
                       ("0.0.0.0/16", "reserved_address"), ("224.0.0.1", "reserved_address"),
                       ("::1", "loopback"), ("2001::/16", "prefix_too_broad")):
        with pytest.raises(AddressError) as caught:
            check_block_shape(net(wide))
        assert caught.value.code == code
    assert [str(n) for n in drop_covered([net("1.2.3.4"), net("1.2.0.0/16")])] == ["1.2.0.0/16"]


def test_desired_state_validation_and_hash() -> None:
    good = {"mode": "enforce", "allow": ["192.0.2.1"],
            "blocks": [{"cidr": "198.51.100.1", "expires_at": 2000},
                       {"cidr": "198.51.100.2", "expires_at": 10}]}
    state = DesiredState.from_payload(good, now=1000)
    assert [str(b.network) for b in state.blocks] == ["198.51.100.1/32"]  # expired dropped
    assert state.state_hash() == DesiredState.from_payload(good, now=1000).state_hash()
    bad_payloads = [
        {"mode": "on"},
        {"mode": "enforce", "extra": 1},
        {"mode": "enforce", "blocks": [{"cidr": "127.0.0.1", "expires_at": None}]},
        {"mode": "enforce", "blocks": [{"cidr": "1.2.3.4; flush ruleset", "expires_at": None}]},
        {"mode": "enforce", "blocks": [{"cidr": "1.2.3.4", "expires_at": "soon"}]},
        {"mode": "enforce", "blocks": [{"cidr": "1.2.3.4", "comment": "x"}]},
        {"mode": "enforce", "allow": ["0.0.0.0/0"]},
        "enforce",
    ]
    for payload in bad_payloads:
        with pytest.raises(DesiredStateError):
            DesiredState.from_payload(payload, now=1000)



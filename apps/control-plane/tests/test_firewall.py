def test_sshd_parser() -> None:
    lines = {
        "Nov  8 10:00:00 h sshd[1]: Failed password for root from 203.0.113.9 port 22 ssh2":
            ("ssh_failed_password", "203.0.113.9", "root"),
        "2026-11-08T10:00:00.1+00:00 h sshd-session[9]: Failed password for invalid user "
        "bob from 2001:db8::5 port 5 ssh2": ("ssh_invalid_user", "2001:db8::5", "bob"),
        "Nov  8 10:00:00 h sshd[1]: Invalid user admin from 198.51.100.4 port 4444":
            ("ssh_invalid_user", "198.51.100.4", "admin"),
        "Nov  8 10:00:00 h sshd[1]: Failed publickey for git from ::ffff:203.0.113.10 port 1":
            ("ssh_failed_password", "203.0.113.10", "git"),
    }
    for line, (kind, ip, user) in lines.items():
        signal = parse_sshd(line)
        assert signal is not None and (signal.kind, signal.ip, signal.detail) == (kind, ip, user)
    for ignored in ("Nov 8 h sshd[1]: Accepted password for root from 203.0.113.9 port 22",
                    "Nov 8 h cron[1]: Failed password for root from 203.0.113.9 port 22",
                    "Nov 8 h sshd[1]: Failed password for root from not-an-ip port 22"):
        assert parse_sshd(ignored) is None


def test_traefik_parser_json_clf_and_sensitive_paths() -> None:
    matcher = PathMatcher(validate_patterns(["/.env", "/.git/", "/wp-login.php"]))
    json_line = json.dumps({"ClientHost": "203.0.113.20", "DownstreamStatus": 404,
                            "RequestPath": "/app/.env?x=1", "RequestMethod": "GET"})
    kinds = [(s.kind, s.ip) for s in parse_traefik(json_line, matcher)]
    assert kinds == [("http_404", "203.0.113.20"), ("http_sensitive_path", "203.0.113.20")]
    # A probe that "succeeds" (200) is still a sensitive-path signal.
    ok = json.dumps({"ClientAddr": "[2001:db8::7]:443", "DownstreamStatus": 200,
                     "RequestPath": "/.git/config"})
    assert [(s.kind, s.ip) for s in parse_traefik(ok, matcher)] == [
        ("http_sensitive_path", "2001:db8::7")]
    clf = '198.51.100.3 - - [08/Nov/2026:10:00:00 +0000] "POST /wp-login.php HTTP/1.1" 401 12'
    assert [s.kind for s in parse_traefik(clf, matcher)] == ["http_401", "http_sensitive_path"]
    assert parse_traefik('{"ClientHost": "203.0.113.20", "DownstreamStatus": 200, '
                         '"RequestPath": "/.envoy/x"}', matcher) == []
    assert parse_traefik("garbage", matcher) == [] and parse_traefik("{bad", matcher) == []
    for bad in (["no-slash"], ["/a b"], [1]):
        with pytest.raises(ValueError):
            validate_patterns(bad)



class FakeRunner:
    """Records nft invocations; models only our table, like the kernel would."""

    def __init__(self, *, available: bool = True, fail: bool = False,
                 fail_check: bool = False) -> None:
        self.calls: list[list[str]] = []
        self.files: list[str] = []
        self.checked: list[str] = []
        self.table: str | None = None
        self.is_available = available
        self.fail = fail
        self.fail_check = fail_check

    def available(self) -> bool:
        return self.is_available

    def run(self, args: list[str]) -> NftResult:
        self.calls.append(list(args))
        if args[:2] == ["-c", "-f"]:  # nft --check: validate only, the table is untouched
            self.checked.append(Path(args[2]).read_text(encoding="ascii"))
            if self.fail_check:
                return NftResult(1, "", "Error: syntax error")
            return NftResult(0, "", "")
        if args[0] == "-f":
            text = Path(args[1]).read_text(encoding="ascii")
            self.files.append(text)
            if self.fail:
                return NftResult(1, "", "Error: Could not process rule")
            self.table = text if "table inet mrk {" in text else None
            return NftResult(0, "", "")
        if args == LIST_ARGS:
            if self.table is None:
                return NftResult(1, "", "Error: No such file or directory")
            listing = {"nftables": [
                {"metainfo": {"version": "1.0.6"}},
                {"set": {"name": "mrk_block_v4", "elem": ["198.51.100.1"]}},
                {"rule": {"expr": [{"counter": {"packets": 7, "bytes": 420}}, {"drop": None}]}},
            ]}
            return NftResult(0, json.dumps(listing), "")
        raise AssertionError(args)


def net(text: str):
    return parse_network(text)



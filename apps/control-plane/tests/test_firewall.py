def test_tailer_starts_at_end_handles_partial_rotation_and_truncation(tmp_path: Path) -> None:
    log = tmp_path / "auth.log"
    log.write_bytes(b"old line ignored\n")
    tailer = FileTailer(log)
    assert tailer.read().lines == []  # history is never re-judged
    with log.open("ab") as handle:
        handle.write(b"one\ntw")
    assert tailer.read().lines == ["one"]
    with log.open("ab") as handle:
        handle.write(b"o\nthree-before-rotate\n")
    # logrotate: rename to .1 (after more data was appended), create a new file.
    with log.open("ab") as handle:
        handle.write(b"tail-of-old\n")
    os.replace(log, tmp_path / "auth.log.1")
    log.write_bytes(b"new-1\n")
    result = tailer.read()
    assert result.rotated is True
    assert result.lines == ["two", "three-before-rotate", "tail-of-old", "new-1"]
    # copytruncate: the same file shrinks.
    log.write_bytes(b"")
    with log.open("ab") as handle:
        handle.write(b"x\n")
    truncated = tailer.read()
    assert truncated.truncated is True and truncated.lines == ["x"]
    # Bounded reads continue next time.
    with log.open("ab") as handle:
        handle.write(b"a" * 10 + b"\n" + b"b" * 10 + b"\n")
    first = tailer.read(max_bytes=11)
    assert first.lines == ["a" * 10] and first.more is True
    assert tailer.read().lines == ["b" * 10]
    log.unlink()
    assert tailer.read().error == "missing"


def test_netinfo_parsers() -> None:
    trie = """Main:
  +-- 0.0.0.0/0 3 0 5
     |-- 172.17.0.1
        /32 host LOCAL
     |-- 172.17.0.0
        /16 link UNICAST
     |-- 203.0.113.5
        /32 host LOCAL
"""
    assert netinfo.parse_fib_trie(trie) == {"172.17.0.1", "203.0.113.5"}
    inet6 = "20010db8000000000000000000000001 02 40 00 80 eth0\nbad\n"
    assert netinfo.parse_if_inet6(inet6) == {"2001:db8::1"}



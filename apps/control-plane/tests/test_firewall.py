def test_manager_enforce_dry_run_off_through_fake_runner(tmp_path: Path) -> None:
    runner = FakeRunner()
    manager = NftManager(runner, tmp_path)
    enforce = DesiredState("enforce", [net("192.0.2.0/24")], [Block(net("198.51.100.1"), None)])
    assert manager.apply(enforce)["action"] == "replace_table"
    assert "198.51.100.1" in runner.files[-1] and runner.table is not None
    status = manager.table_status()
    assert status["present"] is True and status["dropped_packets"] == 7
    assert status["sets"] == {"mrk_block_v4": 1}
    # dry_run applies nothing of ours: the table is removed (idempotently).
    assert manager.apply(DesiredState("dry_run", [], enforce.blocks))["action"] == "delete_table"
    assert runner.table is None and "table inet mrk {" not in runner.files[-1]
    assert manager.table_status() == {"nft_available": True, "present": False}
    assert manager.apply(DesiredState("off"))["action"] == "delete_table"
    assert not list(tmp_path.glob(".ruleset-*"))  # temp ruleset files are removed
    assert all(call[0] in {"-f", "-j", "-c"} for call in runner.calls)
    # Every replace is validated with nft --check first (deletes need no check).
    assert len(runner.checked) == 1 and runner.checked[0] == runner.files[0]



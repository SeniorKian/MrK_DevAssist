def make_helper(tmp_path: Path, runner: FakeRunner, clock: dict, **overrides):
    (tmp_path / "log").mkdir(parents=True, exist_ok=True)
    config = FirewallConfig(key=KEY, state_dir=tmp_path / "state", log_root=tmp_path / "log",
                            proc_net=tmp_path / "proc", host_etc=tmp_path / "etc",
                            clock=lambda: clock["t"], **overrides)
    return create_firewall_app(config, runner=runner, iptables=FakeIptables())


def run_rollback(client: TestClient, app) -> dict | None:
    helper = app.state.helper

    async def go():
        async with helper.lock:
            return await asyncio.to_thread(helper.check_rollback)

    return client.portal.call(go)


PORTS_PAYLOAD = {"enabled": True, "input_policy": "drop", "rules": [
    {"id": "ssh", "protocol": "tcp", "ports": ["22"], "scope": "host"}]}


def test_helper_rollback_timer_confirm_restart_and_recover(tmp_path: Path) -> None:
    clock = {"t": 1_000_000.0}
    runner = FakeRunner()
    app = make_helper(tmp_path, runner, clock)
    with TestClient(app) as client:
        state = {"mode": "dry_run", "ports": PORTS_PAYLOAD}
        refused = signed(client, "POST", "/v1/apply", state)
        assert refused.status_code == 409 and refused.json()["error"] == "rollback_required"
        assert runner.table is None  # nothing loaded
        bad = signed(client, "POST", "/v1/apply", {**state, "rollback_seconds": 5})
        assert bad.status_code == 422
        applied = signed(client, "POST", "/v1/apply", {**state, "rollback_seconds": 120}).json()
        pending = applied["ports"]["pending"]
        assert pending["remaining"] == 120 and applied["ports"]["lkg_key"] == "off"
        assert "chain mrk_input" in runner.table and "policy drop" in runner.table
        assert runner.checked[-1] == runner.files[-1]  # nft -c before the atomic load
        # Re-applying the pending policy (dynamic-defense tick) keeps the timer.
        again = signed(client, "POST", "/v1/apply", {**state, "mode": "enforce"}).json()
        assert again["ports"]["pending"]["token"] == pending["token"]
        clock["t"] += 119
        assert run_rollback(client, app) is None
        clock["t"] += 2
        rolled = run_rollback(client, app)
        assert rolled["reason"] == "timeout" and rolled["outcome"] == "restored"
        assert "chain mrk_input" not in runner.table  # back to the LKG (no port policy)
        assert "chain mrk_prerouting" in runner.table  # dynamic defense untouched
        info = signed(client, "GET", "/v1/info").json()
        assert info["ports"]["pending"] is None and info["ports"]["key"] == "off"
        assert info["ports"]["last_rollback"]["reason"] == "timeout"
        assert info["ssh"] == {"detected": False, "ports": [22]}
        # Confirming in time makes it the LKG.
        armed = signed(client, "POST", "/v1/apply", {**state, "rollback_seconds": 60}).json()
        token = armed["ports"]["pending"]["token"]
        assert signed(client, "POST", "/v1/confirm", {"token": "x" * 16}).json()["error"] == (
            "token_mismatch")
        confirmed = signed(client, "POST", "/v1/confirm", {"token": token}).json()
        assert confirmed["ports"]["pending"] is None
        assert confirmed["ports"]["lkg_key"] == confirmed["ports"]["key"] != "off"
        assert signed(client, "POST", "/v1/confirm", {"token": token}).status_code == 409
        clock["t"] += 1000
        assert run_rollback(client, app) is None  # nothing pending
        # A further risky change, then the helper restarts before it is confirmed.
        risky = {**state, "ports": {**PORTS_PAYLOAD, "rules": [
            {"id": "web", "protocol": "tcp", "ports": ["443"], "scope": "host"}]}}
        signed(client, "POST", "/v1/apply", {**risky, "rollback_seconds": 300})
        assert 'comment "web"' in runner.table
    runner2 = FakeRunner()
    with TestClient(make_helper(tmp_path, runner2, clock)) as client:
        assert 'comment "ssh"' in runner2.table and 'comment "web"' not in runner2.table
        info = signed(client, "GET", "/v1/info").json()
        assert info["ports"]["last_rollback"]["reason"] == "restart"
        # The panel can undo / the console can open everything again.
        opened = signed(client, "POST", "/v1/recover", {"open": True}).json()
        assert opened["rollback"]["reason"] == "recover_open"
        assert runner2.table is None  # dry_run + no port policy: nothing of ours stays
        assert opened["ports"]["lkg_key"] == "off"
        assert signed(client, "POST", "/v1/recover", {"open": "yes"}).status_code == 422
        # Turning the policy off never needs a rollback timer.
        assert signed(client, "POST", "/v1/apply", {"mode": "off"}).status_code == 200
        assert runner2.table is None



def _rule(rule_id: str, ports: list[str], *, source=None, scope="host", action="accept",
          priority=10, enabled=True, protocol="tcp") -> dict:
    return {"id": rule_id, "name": rule_id, "protocol": protocol, "ports": ports,
            "source": source or {"kind": "public"}, "scope": scope, "action": action,
            "enabled": enabled, "priority": priority, "log": False, "log_rate": 10,
            "created_at": 0}


def test_lockout_refusals_ssh_admin_cidr_panel_and_protected_ports() -> None:
    settings = merge_port_settings(DEFAULT_PORT_SETTINGS, {"default_deny_host": True,
                                                           "default_deny_docker": True})
    mgmt = {"id": "m", "name": "Management", "cidrs": ["85.185.239.152/29"]}
    lists = {"m": mgmt}
    admin = ip(ADMIN_IP)
    probes = management_probes(admin, [mgmt])
    assert [str(item) for item in probes] == [ADMIN_IP, "85.185.239.153"]
    assert management_probes(None, []) == [None]

    def problems(rules, **kwargs):
        compiled, _warnings = compile_policy(rules, lists, settings)
        options = {"probes": probes, "ssh_ports": [22], "panel_ports": [443],
                   "protected": set(), **kwargs}
        return [(p["code"], p.get("address"), p.get("port")) for p in
                lockout_problems(compiled, **options)]

    # No SSH rule at all -> refused for both the requester and the management network.
    nothing = problems([])
    assert ("lockout_ssh", ADMIN_IP, None) in nothing
    assert ("lockout_ssh", "85.185.239.153", None) in nothing
    assert ("lockout_panel", ADMIN_IP, 443) in nothing
    # SSH only from the management list: the requester (not in it) would be cut off.
    ssh_mgmt = _rule("ssh", ["22"], source={"kind": "list", "list_id": "m"})
    assert ("lockout_ssh", ADMIN_IP, None) in problems([ssh_mgmt])
    assert ("lockout_ssh", "85.185.239.153", None) not in problems([ssh_mgmt])
    # The temporary allow of the requester does NOT count: a permanent rule must exist.
    compiled, _ = compile_policy([ssh_mgmt], lists, settings, temp_allow=[
        TempAllow(parse_network(ADMIN_IP), int(time.time()) + 600)])
    assert any(p["code"] == "lockout_ssh" for p in lockout_problems(
        compiled, probes=probes, ssh_ports=[22], panel_ports=[], protected=set()))
    # A drop rule placed before the allow wins (first match), like nft.
    admin_rule = _rule("admin", ["22", "443"], source={"kind": "cidrs",
                                                        "cidrs": [ADMIN_IP + "/32"]},
                       scope="both", priority=20)
    panel = _rule("panel", ["443"], source={"kind": "list", "list_id": "m"}, scope="both",
                  priority=30)
    ok = [ssh_mgmt, admin_rule, panel]
    assert problems(ok) == []
    blocker = _rule("block", ["22"], action="drop", priority=1)
    assert ("lockout_ssh", ADMIN_IP, None) in problems([blocker, *ok])
    # Any of the detected sshd ports is enough.
    assert problems(ok, ssh_ports=[6022, 22]) == []
    assert ("lockout_ssh", ADMIN_IP, None) in problems(ok, ssh_ports=[6022])
    # Protected ports: Swarm/Dokploy/DNS must stay reachable unless acknowledged.
    protected = relevant_protected([{"protocol": "tcp", "port": 2377, "loopback_only": False}],
                                   dns_installed=True)
    assert {"swarm-manager", "swarm-overlay", "dokploy", "dns-udp"} <= protected
    closed = {p[0] for p in problems(ok, protected=protected)}
    assert closed == {"protected_port_closed"}
    acknowledged = problems(ok, protected=protected, allowed_closed=sorted(protected))
    assert acknowledged == []
    assert relevant_protected([], dns_installed=False) == set()
    assert "swarm-manager" in relevant_protected(None, dns_installed=False)  # unknown -> all
    # Default accept: nothing can be locked out.
    open_settings = merge_port_settings(settings, {"default_deny_host": False,
                                                   "default_deny_docker": False})
    compiled, _ = compile_policy([], lists, open_settings)
    assert lockout_problems(compiled, probes=probes, ssh_ports=[22], panel_ports=[443],
                            protected=protected) == []
    # Rules referencing an empty list are skipped with a warning.
    _compiled, warnings = compile_policy(
        [_rule("x", ["1"], source={"kind": "list", "list_id": "gone"})], lists, settings)
    assert warnings[0]["code"] == "empty_source_list"
    assert ruleset_diff("a\nb\n", "a\nc\n")[-2:] == ["-b", "+c"]



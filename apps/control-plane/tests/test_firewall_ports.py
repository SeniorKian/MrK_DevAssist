def test_port_apply_lockout_preview_confirm_rollback_and_disable(tmp_path: Path,
                                                                  port_helper) -> None:
    runner: FakeRunner = port_helper["runner"]
    helper = port_helper["app"].state.helper
    client, _app = make_client(tmp_path)
    with client:
        headers = {"X-CSRF-Token": str(login_owner(client)["csrf_token"])}

        def post(path: str, body: dict | None = None):
            return client.post(f"/api/v1/firewall/ports/{path}", headers=headers,
                               json=body or {})

        assert post("apply", {"confirmation": "ENFORCE"}).json()["error"]["code"] == (
            "firewall_not_configured")
        pair(client, headers)
        mgmt = post("lists", {"name": "Management", "cidrs": ["85.185.239.152/29"]}).json()
        post("rules", {"name": "SSH mgmt", "protocol": "tcp", "ports": "22", "scope": "host",
                       "source": {"kind": "list", "list_id": mgmt["id"]}})
        client.put("/api/v1/firewall/ports/settings", headers=headers,
                   json={"default_deny_host": True, "default_deny_docker": True})

        preview = client.get("/api/v1/firewall/ports/preview").json()
        codes = {(p["code"], p.get("address")) for p in preview["problems"]}
        assert ("lockout_ssh", ADMIN_IP) in codes and ("lockout_panel", ADMIN_IP) in codes
        assert preview["panel_ports"] == [80] and preview["ssh_ports"] == [22]
        assert preview["current"].startswith("# Nothing of ours")
        assert "+\t\ttype filter hook input priority filter; policy drop;" in preview["diff"]
        assert preview["temp_allow"] == [f"{ADMIN_IP}/32"]

        assert post("apply", {}).json()["error"]["code"] == "confirmation_required"
        refused = post("apply", {"confirmation": "ENFORCE"})
        assert refused.status_code == 422 and refused.json()["error"]["code"] == "lockout_ssh"
        assert {p["code"] for p in refused.json()["error"]["problems"]} == {
            "lockout_ssh", "lockout_panel"}
        assert runner.table is None  # nothing reached the server

        post("rules", {"name": "Admin", "protocol": "tcp", "ports": "22,80", "scope": "both",
                       "source": {"kind": "cidrs", "cidrs": [ADMIN_IP]}})
        post("rules", {"name": "Panel", "protocol": "tcp", "ports": "80", "scope": "both",
                       "source": {"kind": "list", "list_id": mgmt["id"]}})
        applied = post("apply", {"confirmation": "ENFORCE", "rollback_seconds": 60})
        assert applied.status_code == 200, applied.text
        status = applied.json()
        assert status["active"] is True and 55 <= status["pending"]["remaining"] <= 60
        assert status["problems"] == [] and status["draft"]["differs"] is False
        assert "policy drop" in runner.table and f"{ADMIN_IP} timeout" in runner.table
        tick(client)  # the dynamic-defense loop pushes the pending policy, timer kept
        assert helper.pending is not None and "policy drop" in runner.table
        confirmed = post("confirm").json()
        assert confirmed["pending"] is None and helper.pending is None
        assert post("confirm").json()["error"]["code"] == "no_pending_change"

        # A further change that is never confirmed: the helper rolls back on its own,
        # the panel follows on the next tick instead of pushing the change again.
        post("rules", {"name": "Web", "protocol": "tcp", "ports": "443", "scope": "docker"})
        assert post("apply", {"confirmation": "ENFORCE"}).status_code == 200
        assert "443" in runner.table
        client.portal.call(asyncio.to_thread, helper.check_rollback, time.time() + 10_000)
        assert "443" not in runner.table and "policy drop" in runner.table
        tick(client)
        status = client.get("/api/v1/firewall/ports/status").json()
        assert status["pending"] is None and status["last_rollback"]["reason"] == "timeout"
        assert status["draft"]["differs"] is True and "443" not in runner.table
        events = client.get("/api/v1/firewall/events?action=ports_rollback").json()["items"]
        assert len(events) == 1

        # "Undo now" from the panel.
        assert post("apply", {"confirmation": "ENFORCE"}).status_code == 200
        assert "443" in runner.table
        undone = post("rollback").json()
        assert undone["pending"] is None and "443" not in runner.table

        # Disabling opens everything (no rollback needed); dry_run -> our table is gone.
        disabled = post("disable").json()
        assert disabled["active"] is False and runner.table is None
        audit = [item["action"] for item in client.get("/api/v1/audit-events").json()["items"]]
        for action in ("firewall.ports.apply", "firewall.ports.confirm",
                       "firewall.ports.rollback", "firewall.ports.disable"):
            assert action in audit, action
        assert KEY_TEXT not in json.dumps(audit)
        assert firewall.ACTIVE_SERVICE is not None



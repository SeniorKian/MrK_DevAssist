class FakeIptables(importers.IptablesRunner):
    def __init__(self, chains: dict[str, str] | None = None) -> None:
        self.chains = chains or {}
        self.calls: list[tuple[str, str]] = []

    def available(self, binary: str) -> bool:
        return binary == "/usr/sbin/iptables-nft" and bool(self.chains)

    def list_chain(self, binary: str, chain: str) -> tuple[int, str]:
        assert binary in importers.IPTABLES_BINARIES  # fixed argv only
        self.calls.append((binary, chain))
        if chain not in self.chains:
            return 1, ""
        return 0, self.chains[chain]


def summary(items: list[dict]) -> list[tuple]:
    return [(i["action"], i["protocol"], ",".join(i["ports"]), i["scope"],
             i["source"].get("cidrs", ["any"])[0]) for i in items]


def test_ufw_parser() -> None:
    proposals, skipped = importers.parse_ufw_rules(UFW_RULES)
    assert summary(proposals) == [
        ("accept", "tcp", "22", "host", "any"),
        ("accept", "both", "53", "host", "any"),
        ("accept", "tcp", "14000-14999", "host", "any"),
        ("accept", "tcp", "3000,6022", "host", "85.185.239.152/29"),
        ("drop", "tcp", "25", "host", "203.0.113.0/24"),
        ("accept", "tcp", "22", "host", "any"),  # OpenSSH app profile
        ("accept", "tcp", "2222", "host", "any"),
        ("accept", "tcp", "9000", "docker", "any"),  # route rule
        ("accept", "tcp", "80", "host", "any"),
    ]
    assert proposals[3]["description"] == "mgmt" and proposals[3]["origin"] == "ufw"
    assert "limit" in proposals[6]["description"]
    assert "destination 10.0.0.5" in proposals[8]["description"]
    assert "interface" in proposals[8]["description"]
    assert skipped == ["### tuple ### allow tcp 8080 0.0.0.0/0 any 0.0.0.0/0 out"]
    six, _ = importers.parse_ufw_rules(UFW6_RULES)
    merged = importers.merge_families(proposals + six)
    assert len(merged) == len(proposals) - 1 + 1  # duplicate public 22 rules collapse
    assert importers.parse_ufw_enabled("ENABLED=yes\n") is True
    assert importers.parse_ufw_enabled("ENABLED=no") is False
    assert importers.parse_ufw_enabled(None) is None


def test_iptables_parser_and_reader() -> None:
    proposals, skipped, final_drop = importers.parse_iptables_chain(PAASIFY)
    assert summary(proposals) == [
        ("accept", "tcp", "3000", "docker", "85.185.239.152/29"),
        ("accept", "both", "25,53,80,443", "docker", "any"),
        ("accept", "tcp", "14000-14999", "docker", "any"),
    ]
    assert final_drop is True and len(skipped) == 1 and "! -s" in skipped[0]
    assert importers.jumps_to(DOCKER_USER) is True and importers.jumps_to("") is False
    fake = FakeIptables({"PAASIFY-DOCKER-FW": PAASIFY, "DOCKER-USER": DOCKER_USER})
    found = importers.read_legacy_chain(fake)
    assert found["present"] and found["backend"] == "nft" and found["docker_user_jump"] is True
    assert found["default_drop"] is True and len(found["rules"]) == 3
    assert {chain for _binary, chain in fake.calls} == {"PAASIFY-DOCKER-FW", "DOCKER-USER"}
    with pytest.raises(ValueError):
        importers.IptablesRunner().list_chain("/usr/sbin/iptables-nft", "INPUT")
    with pytest.raises(ValueError):
        importers.IptablesRunner().list_chain("/bin/sh", "DOCKER-USER")
    assert importers.read_legacy_chain(FakeIptables())["available"] is False



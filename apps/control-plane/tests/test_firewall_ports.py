def test_port_ruleset_golden_ipv6_ranges_docker_scope_and_sets() -> None:
    state = DesiredState("dry_run", ports=policy())
    assert render_ruleset(state, now=1000, dynamic=False) == PORTS_GOLDEN
    # dry_run dynamic defense + enabled port policy -> only the port part is loaded.
    assert render_effective(state, now=1000) == PORTS_GOLDEN
    body = "\n".join(line for line in PORTS_GOLDEN.splitlines() if not line.startswith("#"))
    assert set(re.findall(r"\btable (\S+) (\S+)", body)) == {("inet", "mrk")}
    assert "flush" not in body and "ruleset" not in body
    # Logging is its own rule: a rate limit must never decide the verdict.
    for line in body.splitlines():
        if "limit rate" in line:
            verdicts = line.split("log prefix")[0]
            assert " accept" not in verdicts and " drop" not in verdicts


def test_port_ruleset_combined_with_dynamic_defense_and_defaults() -> None:
    combined = DesiredState("enforce", allow=[parse_network("10.0.0.0/8")],
                            blocks=[Block(parse_network("203.0.113.9"), 2000)], ports=policy())
    text = render_ruleset(combined, now=1000)
    # Block/allow sets + prerouting first, then the port chains, all in ONE table.
    assert text.index("chain mrk_prerouting") < text.index("chain mrk_input")
    assert text.count("table inet mrk {") == 1
    # Default accept for both scopes: nothing is closed by installing the policy.
    open_policy = policy(input_policy="accept", forward_policy="accept")
    text = render_ruleset(DesiredState("dry_run", ports=open_policy), now=1000, dynamic=False)
    assert "policy accept;" in text and "policy drop;" not in text
    assert "mrk-drop" not in text and "\t\tcounter drop\n\t}" not in text
    # The forward chain always keeps policy accept (container egress is never filtered).
    assert "hook forward priority filter; policy accept;" in PORTS_GOLDEN
    # A disabled policy (or none) renders nothing of its own.
    assert render_effective(DesiredState("dry_run", ports=policy(enabled=False))) is None
    assert render_effective(DesiredState("dry_run")) is None
    no_icmp = render_ruleset(DesiredState("off", ports=policy(allow_icmp=False,
                                                             trust_docker_bridges=False)),
                             now=1000, dynamic=False)
    assert "nd-neighbor-solicit" in no_icmp and 'iifname "br-*"' not in no_icmp
    # Without ports the payload/hash are unchanged (older helpers keep working).
    assert "ports" not in DesiredState("enforce").to_payload()


def test_port_parsing_and_policy_validation() -> None:
    assert format_ports(parse_ports("443, 80,14000-14999, 14500:15000, 81")) == [
        "80-81", "443", "14000-15000"]
    assert parse_ports([22, "9000-9001"]) == ((22, 22), (9000, 9001))
    for bad in ("", [], "0", "65536", "10-5", "a", [True], "1-2-3", ["22"] * 65):
        with pytest.raises(PortError):
            parse_ports(bad)
    bad_payloads = [
        {"rules": [{"id": "Bad ID", "protocol": "tcp", "ports": ["22"], "scope": "host"}]},
        {"rules": [{"id": "a", "protocol": "icmp", "ports": ["22"], "scope": "host"}]},
        {"rules": [{"id": "a", "protocol": "tcp", "ports": ["22"], "scope": "lan"}]},
        {"rules": [{"id": "a", "protocol": "tcp", "ports": ["22"], "scope": "host",
                    "sources": ["0.0.0.0/0"]}]},
        {"rules": [{"id": "a", "protocol": "tcp", "ports": ["22"], "scope": "host",
                    "sources": ["1.2.3.4; flush ruleset"]}]},
        {"rules": [{"id": "a", "protocol": "tcp", "ports": ["22"], "scope": "host"}] * 2},
        {"input_policy": "reject"}, {"log_rate": 0}, {"extra": 1},
        {"temp_allow": [{"cidr": "1.2.3.4"}]},
    ]
    for payload in bad_payloads:
        with pytest.raises(PortError):
            PortPolicy.from_payload(payload, now=1000)
    parsed = policy()
    assert [str(t.network) for t in parsed.temp_allow] == ["198.51.100.20/32",
                                                          "2001:db8:1::5/128"]
    # The risk key ignores the temporary allows (they expire without a rollback).
    assert parsed.risk_key() == policy(temp_allow=[]).risk_key()
    assert parsed.risk_key() != policy(input_policy="accept").risk_key()
    assert policy(enabled=False).risk_key() == "off"


